export function translatePartner(text: string, language: string): string {
  const index =
    language === "hi" ? 0 : language === "te" ? 1 : language === "kn" ? 2 : -1;
  const count = /^(.*?) (\(\d+\))$/.exec(text);
  if (count) return `${translatePartner(count[1], language)} ${count[2]}`;
  return (
    (index >= 0 ? extra[text]?.[index as 0 | 1 | 2] : undefined) ??
    translate(text, language)
  );
}
