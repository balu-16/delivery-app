import { get, post, buildQuery, sendIdempotent } from './http'
import type { CursorPage, ExportJob, ReportKind, ReportPreviewRow } from '@/types'

// ── Reports: previews per kind + server-side exports (no client-side files) ──

export const REPORT_KINDS: ReportKind[] = ['catalog', 'stock', 'financial', 'picking', 'rider', 'subscription', 'support']

// Snapshot kinds describe current state — the backend rejects date windows for
// them (report-data.ts). Only flow kinds accept from/to.
const SNAPSHOT_KINDS: ReadonlySet<string> = new Set(['catalog', 'stock'])

function windowFor(kind: ReportKind, from?: string, to?: string) {
  return SNAPSHOT_KINDS.has(kind) ? { from: undefined, to: undefined } : { from, to }
}

interface ExportApiRow {
  id: string; kind: string; status: string; row_count: string
  created_at: string; updated_at: string; expires_at: string | null
}

function mapExport(r: ExportApiRow): ExportJob {
  return {
    id: r.id,
    kind: r.kind,
    status: r.status.toLowerCase() as ExportJob['status'],
    rowCount: Number(r.row_count ?? '0') || 0,
    createdAt: r.created_at,
    updatedAt: r.updated_at,
    expiresAt: r.expires_at ?? null,
  }
}

export function reportPreview(kind: ReportKind, filters?: { storeId?: string; from?: string; to?: string; cursor?: string; limit?: number }): Promise<CursorPage<ReportPreviewRow>> {
  const { from, to } = windowFor(kind, filters?.from, filters?.to)
  const qs = buildQuery({ storeId: filters?.storeId, from, to, cursor: filters?.cursor, limit: filters?.limit })
  return get<{ items: ReportPreviewRow[]; nextCursor: string | null }>(`/v1/admin/reports/${kind}${qs}`).then((res) => ({
    items: res.items ?? [],
    nextCursor: res.nextCursor ?? null,
  }))
}

export const createReportExport = (idempotencyKey: string, kind: ReportKind, filters: { storeId?: string; from?: string; to?: string }) => {
  const { from, to } = windowFor(kind, filters.from, filters.to)
  return sendIdempotent<{ id: string }>('POST', '/v1/admin/reports/exports', { kind, storeId: filters.storeId, from, to }, idempotencyKey)
}

export function listReportExports(cursor?: string, limit = 50): Promise<CursorPage<ExportJob>> {
  return get<{ items: ExportApiRow[]; nextCursor: string | null }>(`/v1/admin/reports/exports${buildQuery({ cursor, limit })}`).then((res) => ({
    items: (res.items ?? []).map(mapExport),
    nextCursor: res.nextCursor ?? null,
  }))
}

export const getReportExport = (id: string) => get<ExportApiRow>(`/v1/admin/reports/exports/${id}`).then(mapExport)

/** Download URL for a COMPLETED export — the file is generated by the server. */
export const reportExportDownload = (id: string) => get<{ url: string }>(`/v1/admin/reports/exports/${id}/download`).then((r) => r.url)
