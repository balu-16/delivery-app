import { formatPaise } from '../src/utils/money';

test.each([
  ['0', '₹0.00'],
  ['-0', '₹0.00'],
  ['0000', '₹0.00'],
  ['-0001', '−₹0.01'],
  ['1', '₹0.01'],
  ['99', '₹0.99'],
  ['100', '₹1.00'],
  ['00123456789', '₹12,34,567.89'],
  ['-123456789', '−₹12,34,567.89'],
  ['9223372036854775807', '₹92,23,37,20,36,85,47,758.07'],
  ['-9223372036854775808', '−₹92,23,37,20,36,85,47,758.08'],
  ['123456789012345678901234567890', '₹1,23,45,67,89,01,23,45,67,89,01,23,45,678.90'],
  ['', '—'],
  ['1.5', '—'],
  ['+100', '—'],
  ['--1', '—'],
])('formats %s paise as %s', (input, expected) => {
  expect(formatPaise(input)).toBe(expected);
});
